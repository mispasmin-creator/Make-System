import assert from 'node:assert/strict';
import { addRepairWorkingDays, transitionIssue, overallStatus, stageState, getSummary, getMISRows, durationText } from './repairWorkflow.mjs';
assert.equal(addRepairWorkingDays('2026-10-23T10:45:59+05:30', 1), '2026-10-24T05:15:00.000Z');
assert.equal(addRepairWorkingDays('2026-10-24T10:45:59+05:30', 1), '2026-10-26T05:15:00.000Z');
const actor = { id: 'test-user', fullName: 'Test User' };
const issue = { id: 'test', serial: 'SNW-1', version: 1, approval: { planned: '2026-10-24T05:15:00.000Z' }, repair: {}, management: {} };
assert.equal(overallStatus(issue), 'Pending Approval');
assert.equal(stageState(issue, 'approval', Date.parse('2026-10-23T05:15:00Z')).status, 'Pending');
assert.equal(stageState(issue, 'repair').status, 'Not Started');
assert.throws(() => transitionIssue(issue, 'repair', {}, actor));
const approved = transitionIssue(issue, 'assessment', { repairRequired: 'Yes', whereToSolve: 'Workshop' }, actor, '2026-10-24T05:15:00.000Z');
assert.equal(overallStatus(approved), 'Pending Repair');
assert.equal(approved.repair.planned, '2026-10-28T05:15:00.000Z');
assert.throws(() => transitionIssue(approved, 'assessment', { repairRequired: 'Yes', whereToSolve: 'Workshop' }, actor));
const repaired = transitionIssue(approved, 'repair', { remarks: 'Fixed' }, actor, '2026-10-28T05:15:00.000Z');
assert.equal(overallStatus(repaired), 'Pending Management Acknowledgement');
assert.equal(repaired.activity.at(-1).stageKey, 'SRIF-2');
assert.throws(() => transitionIssue(repaired, 'repair', {}, actor));
const done = transitionIssue(repaired, 'acknowledge', {}, actor, '2026-10-29T05:15:00.000Z');
assert.equal(overallStatus(done), 'Completed');
assert.equal(done.activity.at(-1).stageKey, 'SRIF-3');
assert.throws(() => transitionIssue(done, 'acknowledge', {}, actor));
const noRepair = transitionIssue(issue, 'assessment', { repairRequired: 'No', whereToSolve: 'No issue found' }, actor);
assert.equal(overallStatus(noRepair), 'No Repair Required');
assert.equal(getMISRows([noRepair]).length, 1);
assert.equal(durationText(72 * 3600000), '72h 0m');
const summary = getSummary([issue, approved, repaired, done, noRepair]);
assert.equal(summary['Total Issues'], 5);
assert.equal(summary.Completed, 1);
assert.equal(summary['No Repair Required'], 1);
assert.equal(Object.values(summary).slice(1, -1).reduce((a, b) => a + b, 0), 5);
const historical = { ...issue, repair: { planned: '2026-12-01T05:15:00.000Z' } };
assert.equal(transitionIssue(historical, 'assessment', { repairRequired: 'Yes', whereToSolve: 'Workshop' }, actor).repair.planned, historical.repair.planned);
console.log('PASS: workflow transitions, duplicate actions, calendar rules, planned preservation, delay, overview and MIS.');
