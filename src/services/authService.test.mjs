import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {SYSTEMS,normalizeAccess,hasStageAccess} from '../utils/accessPolicy.mjs';
const values = new Map(), session = new Map();
const storage = map => ({getItem:k=>map.get(k)||null,setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)});
let connected=false, fail=false;
const remoteUser={id:'sheet-user',username:'viewer',fullName:'Viewer',role:'User',status:'Active',systemAccess:{make:false,technical:true,repair:false},permissions:{'technical-new':{view:true,update:true},'technical-all':{view:true,update:false}}};
const context={SYSTEMS,normalizeAccess,hasStageAccess,window:{},localStorage:storage(values),sessionStorage:storage(session),console,isGoogleSheetsConnected:()=>connected,callGoogleAppsScript:async(action,payload)=>{if(fail)throw new Error('network failed');if(action==='login'){assert.equal(payload.username,'viewer');return {user:remoteUser,token:'server-token'};}if(action==='getSession')return {user:remoteUser};return {success:true};}};
vm.createContext(context);
const code=fs.readFileSync(new URL('./authService.js',import.meta.url),'utf8').replace(/^import .*;\r?\n/gm,'').replace(/^export \{ SYSTEMS \};\r?\n/gm,'').replace(/export /g,'');
vm.runInContext(code+'\nglobalThis.service=authService;',context);
values.set('make_system_users_v2',JSON.stringify([{...remoteUser,password:'secret'}]));
await assert.rejects(context.service.login('viewer','wrong'),/Invalid/);
let logged=await context.service.login('viewer','secret');
assert(!logged.password);
assert.equal(context.service.canAccessStage(logged,'technical-new','update'),true);
assert.equal(context.service.canAccessStage(logged,'technical-all','update'),false);
assert.equal(context.service.canAccessStage(logged,'repair-system'),false);
await assert.rejects(context.service.updateUser('sheet-user',{role:'Admin'}),/Only Admin/);
connected=true;
assert.equal(context.service.getCurrentUser(),null,'Legacy sessions must reauthenticate after deployment');
logged=await context.service.login('viewer','server-password');
assert.equal(logged.token,'server-token');
assert.equal(context.service.getCurrentUser().username,'viewer');
fail=true;
await assert.rejects(context.service.login('viewer','server-password'),/network failed/);
fail=false;
await context.service.refreshSession();
context.service.logout();
assert.equal(context.service.getCurrentUser(),null);
console.log('PASS: sheet-authoritative login, no silent offline login on network error, password-free sessions, View/Update, admin-only user edits, legacy re-login and logout.');
